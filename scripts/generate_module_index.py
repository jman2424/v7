"""Write docs/reference/module-index.md from each module's docstring.

Run after adding, removing or re-describing a Python module:

    python scripts/generate_module_index.py

tests/test_reference_docs.py fails when the committed file is out of date, and when a
new module has no docstring to describe it.
"""
from __future__ import annotations

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "reference" / "module-index.md"

PACKAGES = [
    ("app", "Application wiring: factory, settings, middleware, per-tenant container."),
    ("routes", "HTTP endpoints. One Flask blueprint per file."),
    ("handlers", "The three response strategies and the V7 planner and renderer."),
    ("service", "Business logic: conversation, accounts, security, billing, channels, analytics."),
    ("retrieval", "Tenant data stores over the shared Storage layer."),
    ("connectors", "Adapters for external providers."),
    ("scripts", "Operator tools run from the command line. Never imported by the app."),
    ("evals", "Offline agent-quality and performance benchmarks."),
]


def summary(path: Path) -> str:
    doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))) or ""
    first = " ".join(doc.strip().split("\n\n")[0].split())
    return first.rstrip(".") + "." if first else ""


def undocumented() -> list[str]:
    return [path.relative_to(ROOT).as_posix()
            for package, _ in PACKAGES for path in sorted((ROOT / package).glob("*.py"))
            if path.name != "__init__.py" and not summary(path)]


def render() -> str:
    lines = [
        "# Module index",
        "",
        "Generated by `python scripts/generate_module_index.py` from module docstrings.",
        "Do not edit by hand; improve the docstring in the module instead.",
        "",
    ]
    for package, purpose in PACKAGES:
        lines += [f"## `{package}/`", "", purpose, "", "| Module | Purpose |", "|---|---|"]
        for path in sorted((ROOT / package).glob("*.py")):
            if path.name == "__init__.py":
                continue
            text = summary(path).replace("|", "\\|") or "_Undocumented._"
            lines.append(f"| `{package}/{path.name}` | {text} |")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    for name in undocumented():
        print(f"Missing module docstring: {name}")
