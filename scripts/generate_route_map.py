"""Write docs/reference/http-routes.md from the live Flask URL map.

Run after adding, removing or renaming a route:

    python scripts/generate_route_map.py

tests/test_reference_docs.py fails when the committed file is out of date.
"""
from __future__ import annotations

import inspect
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUTPUT = ROOT / "docs" / "reference" / "http-routes.md"

GROUPS = [
    ("Public site and SEO", ("root", "public_seo", "privacy_pages", "static")),
    ("Customer chat and widget", ("webchat", "conversion")),
    ("Inbound provider webhooks", ("whatsapp", "business_channels", "catalog")),
    ("Sign-in and account", ("auth_api", "oidc_login", "admin_ui")),
    ("Owner console (static app)", ("owner_console",)),
    ("Management API", ("admin_api", "email_campaigns", "model_settings", "files", "analytics", "mode", "diag")),
    ("Billing", ("billing", "usage_billing", "ai_budget", "business_applications")),
    ("Agent integrations (MCP and REST)", ("mcp", "mcp_oauth", "vertex_api")),
    ("Health", ("health", "healthz")),
]


def render(app) -> str:
    rows: dict[str, list[tuple[str, str, str]]] = {}
    for rule in app.url_map.iter_rules():
        methods = ", ".join(sorted(rule.methods - {"HEAD", "OPTIONS"})) or "OPTIONS"
        view = app.view_functions[rule.endpoint]
        try:
            source = Path(inspect.getsourcefile(inspect.unwrap(view)) or "").resolve().relative_to(ROOT).as_posix()
        except (TypeError, ValueError):
            source = "flask"
        # A virtualenv may sit inside the repository; only tracked packages count as ours.
        if source.split("/")[0] not in {"app", "routes"}:
            source = "flask"
        blueprint = rule.endpoint.split(".")[0]
        rows.setdefault(blueprint, []).append((rule.rule, methods, f"`{source}` · `{view.__name__}`"))
    lines = [
        "# HTTP routes",
        "",
        "Generated by `python scripts/generate_route_map.py`. Do not edit by hand.",
        "",
        "Every route is registered in `app/app_factory.py`. Authentication, permissions and",
        "tenant checks live in the handler named in the last column and in `service/security.py`.",
        "",
    ]
    seen: set[str] = set()
    grouped = GROUPS + [("Other", tuple(sorted(set(rows) - {name for _, names in GROUPS for name in names})))]
    for title, blueprints in grouped:
        entries = sorted(entry for name in blueprints for entry in rows.get(name, []))
        seen.update(blueprints)
        if not entries:
            continue
        lines += [f"## {title}", "", "| Path | Methods | Handler |", "|---|---|---|"]
        lines += [f"| `{path}` | {methods} | {handler} |" for path, methods, handler in entries]
        lines.append("")
    return "\n".join(lines)


def build() -> str:
    os.environ.setdefault("SECRET_KEY", "route-map-generation-only-" * 2)
    from app import create_app
    return render(create_app({"TESTING": True}))


if __name__ == "__main__":
    OUTPUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
