def agent(intent='answer', stage='assist', action='await_customer_question', *,
          offerings=None, selected=None, requirements=None, update=None, selection='keep', evidence=None):
    return {'intent': intent, 'stage': stage, 'next_action': action,
            'offering_ids': offerings or [], 'selected_offering_id': selected,
            'selection_update': selection, 'selection_evidence': evidence,
            'requirements': requirements or [], 'requirements_update': update}


def reply(answer, sources, *, state=None, navigation=None, requested_action=None, kind='answer'):
    return {'answer': answer, 'sources': sources, 'kind': kind, 'agent': state or agent(),
            'navigation': navigation or [], 'requested_action': requested_action, 'statement_ids': []}


