DO $api_roles$
DECLARE api_role TEXT;
BEGIN
  FOREACH api_role IN ARRAY ARRAY['anon','authenticated','service_role'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=api_role) THEN
      IF pg_has_role(api_role, 'v7_backend', 'MEMBER') THEN
        RAISE EXCEPTION 'Data API role must not inherit v7_backend';
      END IF;
      EXECUTE format('REVOKE ALL ON SCHEMA v7_private FROM %I', api_role);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA v7_private FROM %I', api_role);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA v7_private FROM %I', api_role);
      EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA v7_private FROM %I', api_role);
    END IF;
  END LOOP;
END
