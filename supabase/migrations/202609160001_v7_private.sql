CREATE SCHEMA IF NOT EXISTS v7_private;
REVOKE ALL ON SCHEMA v7_private FROM PUBLIC;
SET LOCAL search_path = v7_private, pg_catalog;

DO $roles$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'v7_backend') THEN
    CREATE ROLE v7_backend NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='v7_backend'
             AND (rolsuper OR rolbypassrls OR rolcreaterole OR rolcreatedb OR rolcanlogin)) THEN
    RAISE EXCEPTION 'Existing v7_backend role has unexpected privileges';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_auth_members m JOIN pg_roles r ON r.oid=m.member WHERE r.rolname='v7_backend') THEN
    RAISE EXCEPTION 'v7_backend must not inherit another role';
  END IF;
END
$roles$;
GRANT USAGE ON SCHEMA v7_private TO v7_backend;
ALTER DEFAULT PRIVILEGES IN SCHEMA v7_private REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA v7_private REVOKE ALL ON SEQUENCES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA v7_private REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;

